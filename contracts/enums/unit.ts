export enum Unit {
  ML = 'ml',       // milliliters (for liquids like shampoo, conditioner)
  L = 'l',         // liters (bulk liquids)
  G = 'g',         // grams (for powders or creams)
  KG = 'kg',       // kilograms (bulk products)
  UNIT = 'unit',   // single item (like comb, brush, razor)
  BOX = 'box',     // packaged items
}